// Current language
let currentLanguage = 'en';

// Function to set language
function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    updatePageContent();
}

// Function to get translation
function getTranslation(key) {
    const keys = key.split('.');
    let value = translations[currentLanguage];
    
    for (const k of keys) {
        if (value && typeof value === 'object') {
            value = value[k];
        } else {
            return key; // Return key if translation not found
        }
    }
    
    return value || key;
}

// Function to update page content
function updatePageContent() {
    // Update elements with data-lang attribute
    document.querySelectorAll('[data-lang]').forEach(element => {
        const key = element.getAttribute('data-lang');
        const translation = getTranslation(key);
        
        if (element.tagName === 'INPUT' && element.type === 'submit') {
            element.value = translation;
        } else if (element.tagName === 'META' && element.name === 'description') {
            element.content = translation;
        } else {
            element.textContent = translation;
        }
    });
    
    // Update document title if it has data-lang
    if (document.title && document.title.includes('data-lang')) {
        // Handle dynamic title updates if needed
    }
    
    // Update HTML lang attribute
    document.documentElement.lang = currentLanguage;
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', function() {
    const savedLang = localStorage.getItem('language') || 'en';
    setLanguage(savedLang);
});